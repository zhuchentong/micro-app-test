import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Components from "unplugin-vue-components/vite";
import tailwindcss from "@tailwindcss/vite";
import { defineConfig } from "@vizejs/vite-plugin/vite-plus";

// Tailwind 扫描 @repo/ui 组件源码:vite root 外的目录,显式 @source 注册。
// config 加载时生成 src/ui.source.css(gitignored),供 style.css @import 消费。
const uiSrcDir = join(dirname(fileURLToPath(import.meta.url)), "../../packages/ui/src");
writeFileSync(
  join(dirname(fileURLToPath(import.meta.url)), "src/ui.source.css"),
  `/* generated by vite.config:请勿提交或手改 */\n@source ${JSON.stringify(uiSrcDir)};\n`,
);

export default defineConfig(
  {
    // wujie 通过 fetch 拉取子应用 HTML,cors 必须开启
    server: { port: 7201, host: true, cors: true },
    plugins: [
      tailwindcss(),
      // @repo/ui 组件免 import 按需引入(dirs 递归:components/ui 上游件原名,components/app 自研件前缀名)
      // dts 生成物入 src/types/generated/(gitignored),dev/build 启动时自动重新生成
      Components({
        dirs: ["../../packages/ui/src/components"],
        dts: "src/types/generated/components.d.ts",
      }),
    ],
  },
  { tasks: false },
);
